import { Truck, Driver, Customer, Product } from "./entities";

export type OrderState = 1 | 2 | 3 | 4;

export const ORDER_STATE_LABELS: Record<OrderState, string> = {
  1: "Pendiente de pesaje inicial",
  2: "Con pesaje inicial registrado",
  3: "Cerrada para carga",
  4: "Finalizada",
};

export interface OrderDetail {
  id?: number;
  orderId?: number;
  accumulatedMass: number; // kg
  density: number; // kg/m3 (0 - 1)
  temperature: number; // °C
  flowRate: number; // kg/h
  timestamp: string; // ISO 8601
}

export interface Order {
  id: number;
  orderNumber: number;
  externalCode?: string;
  state: OrderState;

  // Associated entities
  truck: Truck;
  driver: Driver;
  customer: Customer;
  product: Product;

  // Scheduled & preset values
  scheduledDate: string; // ISO or date string
  preset: number; // kg to load

  // Initial weighing (State 2)
  initialWeight?: number; // kg (tara)
  initialWeightTime?: string;
  activationPassword?: string; // 5-digit pin generated by backend

  // Load telemetry timestamps
  loadStartTime?: string;
  loadEndTime?: string;

  // Header latest values (Live in State 2)
  lastAccumulatedMass?: number;
  lastDensity?: number;
  lastTemperature?: number;
  lastFlowRate?: number;
  lastTelemetryTimestamp?: string;

  // Final weighing (State 4)
  finalWeight?: number; // kg (bruto)
  finalWeightTime?: string;

  // Creation timestamp
  receivedAt: string;
}
